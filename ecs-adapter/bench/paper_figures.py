def _pct(s: dict | None, key: str = "accepted") -> float | None:
    return 100 * s[key] / s["n"] if s and s.get("n") else None


def _f(x: float) -> str:
    return f"{x:.3f}"


# ------------------------------------------------------------------ Task 1 forest
def forest_t1(res: dict) -> str:
    """Q2: acceptance with its uncertainty, per pool and configuration - a forest plot, so
    that overlapping intervals are seen as overlapping rather than read off a table."""
    S = res["summary"]
    W, rowh, gap = 5.6, 0.26, 0.22
    panels = [("model-only", "E", ["A", "B", "T", "C"]), ("full system", "F", ["T", "C"])]
    pools = [("id", "id"), ("drift", "drift"), ("dev", "dev"), ("ood", "ood"), ("all", "\\textbf{all}")]
    L = ["% GENERATED - fig:t1-forest", "\\begin{tikzpicture}[font=\\scriptsize]"]
    x0 = 0.0
    for title, mode, arms in panels:
        y = 0.0
        L.append(f"\\node[font=\\scriptsize\\bfseries, anchor=south] at ({x0 + W/2:.2f},0.25) {{{title}}};")
        tops = []
        for key, lab in pools:
            top = y
            L.append(f"\\node[anchor=east] at ({x0 - 0.1:.2f},{y - (len(arms)-1)*rowh/2:.2f}) {{{lab}}};")
            for i, arm in enumerate(arms):
                yy = y - i * rowh
                s = S.get(f"t1/{key}/{arm}/{mode}")
                if not s or not s["n"]:
                    L.append(f"\\node[font=\\tiny, text=black!50] at ({x0 + W/2:.2f},{yy:.2f}) {{{MISSING}}};")
                    continue
                p = 100 * s["accepted"] / s["n"]
                lo, hi = (100 * v for v in s["acc_ci"])
                L.append(f"\\draw[{ARM_COL[arm]}, line width=0.7pt] ({x0 + W*lo/100:.3f},{yy:.2f}) -- ({x0 + W*hi/100:.3f},{yy:.2f});")
                L.append(f"\\fill[{ARM_COL[arm]}] ({x0 + W*p/100:.3f},{yy:.2f}) circle (1.5pt);")
            y -= len(arms) * rowh + gap
            tops.append((top, y + gap))
            if key == "ood":
                L.append(f"\\draw[black!35] ({x0:.2f},{y + gap/2:.2f}) -- ({x0 + W:.2f},{y + gap/2:.2f});")
        bottom = y + gap - 0.15
        for t in (0, 25, 50, 75, 100):
            xx = x0 + W * t / 100
            L.append(f"\\draw[gridc] ({xx:.2f},0.15) -- ({xx:.2f},{bottom:.2f});")
            L.append(f"\\node[anchor=north, font=\\tiny] at ({xx:.2f},{bottom:.2f}) {{{t}}};")
        L.append(f"\\node[anchor=north, font=\\tiny] at ({x0 + W/2:.2f},{bottom - 0.25:.2f}) {{runs accepted (\\%), Wilson 95\\%}};")
        x0 += W + 1.4
    yl = bottom - 0.75
    xl = 0.0
    for arm in ("A", "B", "T", "C"):
        L.append(f"\\fill[{ARM_COL[arm]}] ({xl:.2f},{yl:.2f}) circle (1.5pt); \\node[anchor=west] at ({xl + 0.08:.2f},{yl:.2f}) {{{ARM_TXT[arm]}}};")
        xl += 2.3
    L.append("\\end{tikzpicture}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ dev vs held-out
def dumbbell(res: dict) -> str:
    """Q3: does a configuration keep its Task-2 result on changes it was not developed on?
    One row per configuration; the development and held-out acceptance joined by a line."""
    S = res["summary"]
    W, rowh = 5.2, 0.42
    L = ["% GENERATED - fig:dumbbell", "\\begin{tikzpicture}[font=\\scriptsize]"]
    n = len(T2_ARMS)
    for t in (0, 25, 50, 75, 100):
        xx = W * t / 100
        L.append(f"\\draw[gridc] ({xx:.2f},0.25) -- ({xx:.2f},{-(n-1)*rowh - 0.25:.2f});")
        L.append(f"\\node[anchor=north, font=\\tiny] at ({xx:.2f},{-(n-1)*rowh - 0.25:.2f}) {{{t}}};")
    for i, arm in enumerate(T2_ARMS):
        y = -i * rowh
        L.append(f"\\node[anchor=east] at (-0.1,{y:.2f}) {{{ARM_TXT[arm]}}};")
        d, h = S.get(f"t2/r3/{arm}/F"), S.get(f"t2/ho/{arm}/F")
        pts = []
        for s, col, dy, filled in ((d, "setDev", 0.07, False), (h, "setHo", -0.07, True)):
            if not s or not s["n"]:
                continue
            p = 100 * s["accepted"] / s["n"]
            lo, hi = (100 * v for v in s["acc_ci"])
            L.append(f"\\draw[{col}!55, line width=0.5pt] ({W*lo/100:.3f},{y+dy:.2f}) -- ({W*hi/100:.3f},{y+dy:.2f});")
            pts.append((W * p / 100, y + dy, col, filled))
        if len(pts) == 2:
            L.append(f"\\draw[black!45, line width=1.2pt] ({pts[0][0]:.3f},{pts[0][1]:.2f}) -- ({pts[1][0]:.3f},{pts[1][1]:.2f});")
        for x, yy, col, filled in pts:
            L.append(f"\\draw[{col}, line width=0.9pt, fill={'%s' % col if filled else 'white'}] ({x:.3f},{yy:.2f}) circle (2.1pt);")
        lab = f"{d['accepted']}/{d['n']}" if d else MISSING
        lab2 = f"{h['accepted']}/{h['n']}" if h else MISSING
        L.append(f"\\node[anchor=west, font=\\tiny] at ({W + 0.1:.2f},{y:.2f}) {{{lab} $\\rightarrow$ {lab2}}};")
    yl = -(n - 1) * rowh - 0.85
    L.append(f"\\node[anchor=north, font=\\tiny] at ({W/2:.2f},{-(n-1)*rowh - 0.48:.2f}) {{runs accepted, full system (\\%), Wilson 95\\%}};")
    L.append(f"\\draw[setDev, line width=0.9pt, fill=white] (0.2,{yl - 0.1:.2f}) circle (2.1pt); \\node[anchor=west] at (0.3,{yl - 0.1:.2f}) {{development (6 changes)}};")
    L.append(f"\\draw[setHo, line width=0.9pt, fill=setHo] (3.0,{yl - 0.1:.2f}) circle (2.1pt); \\node[anchor=west] at (3.1,{yl - 0.1:.2f}) {{held out (4 changes)}};")
    L.append("\\end{tikzpicture}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ model-only -> full system
def transitions(res: dict) -> str:
    """Q5: what repair and the deterministic layer do to a run. Each cell counts the
    (change, seed) pairs whose model-only run ended at the row's level and whose
    full-system run ended at the column's; above the diagonal the system lifted the run."""
    R = res.get("runs", {})
    order = ["report", "support", "functional", "accepted"]
    short = {"report": "rep.", "support": "supp.", "functional": "funct.", "accepted": "acc."}
    L = ["% GENERATED - fig:transitions", "\\begin{tikzpicture}[font=\\scriptsize]"]
    c = 0.52
    for k, arm in enumerate(["B", "C", "14B", "T"]):
        x0 = k * (4 * c + 0.75)
        M = Counter()
        for pool in ("all",):
            E = {(r["source"], r["seed"]): r["level"] for r in R.get(f"t2/{pool}/{arm}/E", [])}
            F = {(r["source"], r["seed"]): r["level"] for r in R.get(f"t2/{pool}/{arm}/F", [])}
            for key in E.keys() & F.keys():
                if E[key] in order and F[key] in order:
                    M[(E[key], F[key])] += 1
        tot = sum(M.values())
        L.append(f"\\node[anchor=south] at ({x0 + 2*c:.2f},{c*0.5 + 0.05:.2f}) {{{ARM_TXT[arm]}}};")
        if not tot:
            L.append(f"\\draw[dashed, black!40] ({x0:.2f},{c/2:.2f}) rectangle ({x0 + 4*c:.2f},{-3.5*c:.2f});")
            L.append(f"\\node at ({x0 + 2*c:.2f},{-1.5*c:.2f}) {{{MISSING}}};")
            continue
        mx = max(M.values())
        for i, rl in enumerate(order):            # rows: model-only
            for j, cl in enumerate(order):        # cols: full system
                v = M.get((rl, cl), 0)
                shade = 0 if not v else int(15 + 70 * v / mx)
                col = "lvAcc" if j > i else ("armT" if j < i else "black")
                if j == i:
                    shade = shade // 3
                L.append(f"\\fill[{col}!{shade}] ({x0 + j*c:.2f},{-i*c + c/2:.2f}) rectangle ++({c:.2f},{-c:.2f});")
                L.append(f"\\draw[black!20] ({x0 + j*c:.2f},{-i*c + c/2:.2f}) rectangle ++({c:.2f},{-c:.2f});")
                if v:
                    L.append(f"\\node[{'text=white' if shade > 60 and i != j else ''}] at ({x0 + j*c + c/2:.2f},{-i*c:.2f}) {{{v}}};")
        if k == 0:
            for i, rl in enumerate(order):
                L.append(f"\\node[anchor=east, font=\\tiny] at ({x0 - 0.05:.2f},{-i*c:.2f}) {{{short[rl]}}};")
            L.append(f"\\node[rotate=90, font=\\tiny] at ({x0 - 0.75:.2f},{-1.5*c:.2f}) {{model only}};")
        for j, cl in enumerate(order):
            L.append(f"\\node[anchor=north, font=\\tiny] at ({x0 + j*c + c/2:.2f},{-3.5*c:.2f}) {{{short[cl]}}};")
    L.append(f"\\node[font=\\tiny] at ({2*(4*c+0.75) - 0.35:.2f},{-3.5*c - 0.42:.2f}) {{full system}};")
    L.append("\\end{tikzpicture}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ ablation
def ablation(res: dict) -> str:
    """Q5: each part of arm C removed in turn. The bar is the change in acceptance, in
    percentage points, that removing it causes; left of zero means the part was helping."""
    S = res["summary"]
    rows = [
        ("training (\\armC{} $\\rightarrow$ \\armB{})", [("t1", "t1/all/C/E", "t1/all/B/E"), ("r3", "t2/r3/C/F", "t2/r3/B/F"), ("ho", "t2/ho/C/F", "t2/ho/B/F")]),
        ("repair and deterministic layer", [("t1", "t1/all/C/F", "t1/all/C/E"), ("r3", "t2/r3/C/F", "t2/r3/C/E"), ("ho", "t2/ho/C/F", "t2/ho/C/E")]),
    ]
    SET = {"t1": ("setT1", "Task 1"), "r3": ("setDev", "Task 2, development"), "ho": ("setHo", "Task 2, held out")}
    vals = []
    for _, bars in rows:
        for st, a, b in bars:
            pa, pb = _pct(S.get(a)), _pct(S.get(b))
            vals.append(None if pa is None or pb is None else pb - pa)
    m = max([abs(v) for v in vals if v is not None] + [20])
    m = 20 * (int(m // 20) + 1)
    W = 5.0
    sc = (W / 2) / m
    L = ["% GENERATED - fig:ablation", "\\begin{tikzpicture}[font=\\scriptsize]"]
    bh, gap = 0.2, 0.32
    y = 0.0
    k = 0
    xs = [W / 2 + t * sc for t in range(-m, m + 1, 20)]
    for _, bars in rows:
        y -= 0.05
        for st, a, b in bars:
            v = vals[k]; k += 1
            col = SET[st][0]
            if v is None:
                L.append(f"\\node[font=\\tiny] at ({W/2:.2f},{y:.2f}) {{{MISSING}}};")
            else:
                L.append(f"\\fill[{col}] ({W/2:.3f},{y - bh/2:.2f}) rectangle ({W/2 + v*sc:.3f},{y + bh/2:.2f});")
                anchor = "east" if v < 0 else "west"
                L.append(f"\\node[anchor={anchor}, font=\\tiny] at ({W/2 + v*sc + (-0.04 if v < 0 else 0.04):.3f},{y:.2f}) {{{v:+.0f}}};")
            y -= bh + 0.04
        y -= gap
    y_end = y + gap
    yy = 0.15
    for t, x in zip(range(-m, m + 1, 20), xs):
        L.append(f"\\draw[gridc] ({x:.2f},{yy:.2f}) -- ({x:.2f},{y_end:.2f});")
        L.append(f"\\node[anchor=north, font=\\tiny] at ({x:.2f},{y_end:.2f}) {{{t:+d}}};")
    L.append(f"\\draw[black!70] ({W/2:.2f},{yy:.2f}) -- ({W/2:.2f},{y_end:.2f});")
    # labels after grid so they sit on top
    y = 0.0
    for name, bars in rows:
        y -= 0.05
        mid = y - (len(bars) - 1) * (bh + 0.04) / 2
        L.append(f"\\node[anchor=east, align=right, text width=2.6cm] at (-0.1,{mid:.2f}) {{{name}}};")
        y -= len(bars) * (bh + 0.04) + gap
    L.append(f"\\node[anchor=north, font=\\tiny] at ({W/2:.2f},{y_end - 0.25:.2f}) {{change in runs accepted when the part is removed (percentage points)}};")
    xl, yl = -2.6, y_end - 0.75
    for st in ("t1", "r3", "ho"):
        col, lab = SET[st]
        L.append(f"\\fill[{col}] ({xl:.2f},{yl - 0.07:.2f}) rectangle ++(0.25,0.14); \\node[anchor=west] at ({xl + 0.3:.2f},{yl:.2f}) {{{lab}}};")
        xl += 2.5
    L.append("\\end{tikzpicture}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ where refusals stop
def rungs(res: dict) -> str:
    """Q1: of the runs that were refused, the rung that stopped them. The V4 segment is the
    share that every structural check passed and only detection replay caught."""
    R = res.get("runs", {})
    cats = [("none", "no valid IR", "black!25"), ("V1", "V1", "lvRep"), ("V2", "V2", "armB!45"),
            ("V3", "V3", "arm14!55"), ("V4", "V4 only", "armT!80")]
    groups = [("Task 1", [("C", ["t1/all/C/F"]), ("T", ["t1/all/T/F"])]),
              ("Task 2", [(a, [f"t2/all/{a}/F"]) for a in ("A", "B", "C", "14B", "T")])]
    W, rowh = 5.0, 0.36
    L = ["% GENERATED - fig:rungs", "\\begin{tikzpicture}[font=\\scriptsize]"]
    y = 0.0
    for gname, items in groups:
        L.append(f"\\node[anchor=west, font=\\scriptsize\\itshape] at (-2.6,{y:.2f}) {{{gname}}};")
        y -= rowh
        for arm, keys in items:
            rs = [r for k in keys for r in R.get(k, []) if r["level"] != "accepted"]
            L.append(f"\\node[anchor=east] at (-0.1,{y:.2f}) {{{ARM_TXT[arm]}}};")
            if not rs:
                L.append(f"\\draw[dashed, black!40] (0,{y-0.12:.2f}) rectangle ({W},{y+0.12:.2f}); \\node at ({W/2},{y:.2f}) {{{MISSING}}};")
                y -= rowh
                continue
            cnt = Counter((r["rung"] if r["rung"] in ("V1", "V2", "V3", "V4") else ("V3" if r["rung"] == "V3.5" else "none")) for r in rs)
            x = 0.0
            for key, _, col in cats:
                w = W * cnt.get(key, 0) / len(rs)
                if w > 0:
                    L.append(f"\\fill[{col}] ({x:.3f},{y-0.12:.2f}) rectangle ({x+w:.3f},{y+0.12:.2f});")
                    if w > 0.22:
                        L.append(f"\\node[font=\\tiny{', text=white' if key == 'V4' else ''}] at ({x+w/2:.3f},{y:.2f}) {{{cnt[key]}}};")
                x += w
            L.append(f"\\node[anchor=west, font=\\tiny] at ({W + 0.05:.2f},{y:.2f}) {{{len(rs)}}};")
            y -= rowh
    x = -2.6
    y -= 0.1
    for _, lab, col in cats:
        L.append(f"\\fill[{col}] ({x:.2f},{y-0.07:.2f}) rectangle ++(0.25,0.14); \\node[anchor=west] at ({x+0.28:.2f},{y:.2f}) {{{lab}}};")
        x += 1.75
    L.append("\\end{tikzpicture}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ fields the rules read
def fields(res: dict) -> str:
    """Q3/Q4: on the held-out changes, every field a detection rule reads, and how many of
    each configuration's two full-system runs mapped it correctly. A cross marks a run that
    put the field's value somewhere wrong. This is where 4/8 against 8/8 comes from."""
    R = res.get("runs", {})
    names = {"r4_haproxy_json": "HAProxy", "r4_caddy_json": "Caddy", "r4_postfix_37": "Postfix", "r4_dovecot_24": "Dovecot"}
    arms = ["B", "C", "14B", "T"]
    rows = []
    for sid in names:
        tg = set()
        for d in sorted((ROOT / "bench" / "scenarios").glob(f"{sid}__*")):
            try:
                tg |= set(json.loads((d / "expected.json").read_text())["targets"])
            except (OSError, KeyError, json.JSONDecodeError):
                pass
        rows += [(sid, f) for f in sorted(tg)]
    c, rh = 0.62, 0.27
    L = ["% GENERATED - fig:fields", "\\begin{tikzpicture}[font=\\scriptsize]"]
    for j, arm in enumerate(arms):
        L.append(f"\\node[rotate=50, anchor=south west, inner sep=1pt] at ({j*c + c/2 - 0.1:.2f},0.12) {{{ARM_TXT[arm]}}};")
    last = None
    y = 0.0
    for sid, f in rows:
        if sid != last:
            y -= 0.08
            L.append(f"\\node[anchor=west, font=\\scriptsize\\itshape] at (-3.0,{y - rh/2:.2f}) {{{names[sid]}}};")
            y -= rh
            last = sid
        L.append(f"\\node[anchor=east, font=\\tiny\\ttfamily] at (-0.05,{y - rh/2:.2f}) {{{f.replace('_', chr(92) + '_')}}};")
        for j, arm in enumerate(arms):
            runs = [r for r in R.get(f"t2/r4/{arm}/F", []) if r["source"] == sid]
            x = j * c
            if not runs:
                L.append(f"\\node[font=\\tiny] at ({x + c/2:.2f},{y - rh/2:.2f}) {{??}};")
                continue
            ok = sum(f in r["cf"] for r in runs)
            bad = sum(f in r["wf"] for r in runs)
            shade = int(100 * ok / len(runs))
            L.append(f"\\fill[lvAcc!{shade}] ({x + 0.04:.2f},{y - 0.03:.2f}) rectangle ({x + c - 0.04:.2f},{y - rh + 0.03:.2f});")
            L.append(f"\\draw[black!25] ({x + 0.04:.2f},{y - 0.03:.2f}) rectangle ({x + c - 0.04:.2f},{y - rh + 0.03:.2f});")
            if bad:
                L.append(f"\\node[text=armT, font=\\scriptsize\\bfseries] at ({x + c/2:.2f},{y - rh/2:.2f}) {{$\\times$}};")
        y -= rh
    y -= 0.2
    L.append(f"\\fill[lvAcc] (-1.7,{y:.2f}) rectangle ++(0.25,-0.16); \\node[anchor=west, font=\\tiny] at (-1.42,{y - 0.08:.2f}) {{both runs correct}};")
    L.append(f"\\fill[lvAcc!50] (0.6,{y:.2f}) rectangle ++(0.25,-0.16); \\node[anchor=west, font=\\tiny] at (0.88,{y - 0.08:.2f}) {{one}};")
    L.append(f"\\draw[black!25] (1.55,{y:.2f}) rectangle ++(0.25,-0.16); \\node[anchor=west, font=\\tiny] at (1.83,{y - 0.08:.2f}) {{none}};")
    L.append(f"\\node[text=armT, font=\\scriptsize\\bfseries] at (2.55,{y - 0.08:.2f}) {{$\\times$}}; \\node[anchor=west, font=\\tiny] at (2.65,{y - 0.08:.2f}) {{a run mapped it wrongly}};")
    L.append("\\end{tikzpicture}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ training curves
def _trainer(roots: list[Path], name: str) -> dict | None:
    for r in roots:
        for base in (r.parent / "metrics" / "training", r.parent.parent / "metrics" / "training"):
            p = base / f"{name}.trainer_state.json"
            if p.is_file():
                return json.loads(p.read_text(encoding="utf-8"))
    return None


def training(roots: list[Path]) -> str:
    """Section 'What the specialists learn from': the two training steps of each stage as one
    curve, the second step continuing from the first's last epoch."""
    panels = [("first stage (interpret)", "gold-interpret", "edit-interpret", "edit and repair", "org9-interpret"),
              ("second stage (map)", "gold-map", "edit2-map", "dictionary", "org9-map")]
    L = ["% GENERATED - fig:training", "\\begin{tikzpicture}",
         "\\begin{groupplot}[group style={group size=2 by 1, horizontal sep=1.1cm}, width=0.56\\columnwidth, height=3.9cm,",
         " ymode=log, xlabel={epoch}, every axis/.append style={font=\\scriptsize}, xmin=0, xmax=7, grid=major, grid style={gridc},",
         " legend style={font=\\tiny, at={(0.98,0.98)}, anchor=north east, draw=none, fill=white, fill opacity=0.8, text opacity=1}]"]
    for title, first, second, lab2, third in panels:
        L.append(f"\\nextgroupplot[title={{{title}}}, title style={{font=\\scriptsize}}{', ylabel={loss}' if first == 'gold-interpret' else ''}]")
        off = 0.0
        drew = False
        for name, col, lab in ((first, "setT1", "generator mappings"), (second, "armB", lab2), (third, "armC", "organisation logs")):
            st = _trainer(roots, name)
            if not st:
                continue
            h = st.get("log_history", [])
            tr = [(off + e["epoch"], e["loss"]) for e in h if "loss" in e and e.get("loss", 0) > 0]
            ev = [(off + e["epoch"], e["eval_loss"]) for e in h if "eval_loss" in e]
            if tr:
                step = max(1, len(tr) // 60)
                L.append(f"\\addplot[{col}, line width=0.7pt, mark=none] coordinates {{{' '.join(f'({x:.3f},{y:.4f})' for x, y in tr[::step])}}};")
                L.append(f"\\addlegendentry{{{lab}}}")
            if ev:
                L.append(f"\\addplot[{col}, only marks, mark=*, mark size=1.6pt, forget plot] coordinates {{{' '.join(f'({x:.3f},{y:.4f})' for x, y in ev)}}};")
            off = (tr[-1][0] if tr else off)
            drew = True
        if drew:
            L.append(f"\\draw[black!40, dashed] (axis cs:3,1e-3) -- (axis cs:3,10);")
        else:
            L.append("\\node at (axis cs:2.5,0.1) {\\missingnum};")
    L.append("\\end{groupplot}\\end{tikzpicture}")
