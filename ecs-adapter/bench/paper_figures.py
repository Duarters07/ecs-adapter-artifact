# ------------------------------------------------------------------ cost per run
def cost(res: dict) -> str:
    """Section 'Cost': wall-clock time of every full-system Task-2 run, per configuration, on
    one RTX 4090; log scale, median marked. Inference is paid per source, so this is the time
    from a detected change to a decision."""
    R = res.get("runs", {})
    lo, hi = 0.5, 120.0
    W = 5.4

    def X(m: float) -> float:
        m = min(max(m, lo), hi)
        return W * (log10(m) - log10(lo)) / (log10(hi) - log10(lo))
    arms = ["A", "B", "C", "14B", "T"]
    rowh = 0.36
    L = ["% GENERATED - fig:cost", "\\begin{tikzpicture}[font=\\scriptsize]"]
    n = len(arms)
    for t in (1, 2, 5, 10, 20, 50, 100):
        L.append(f"\\draw[gridc] ({X(t):.2f},0.2) -- ({X(t):.2f},{-(n-1)*rowh - 0.2:.2f});")
        L.append(f"\\node[anchor=north, font=\\tiny] at ({X(t):.2f},{-(n-1)*rowh - 0.2:.2f}) {{{t}}};")
    for i, arm in enumerate(arms):
        y = -i * rowh
        L.append(f"\\node[anchor=east] at (-0.1,{y:.2f}) {{{ARM_TXT[arm]}}};")
        ws = sorted(r["wall_s"] / 60 for k in ("all",) for r in R.get(f"t2/{k}/{arm}/F", []) if r.get("wall_s"))
        if not ws:
            L.append(f"\\node at ({W/2:.2f},{y:.2f}) {{{MISSING}}};")
            continue
        for k2, m in enumerate(ws):
            jit = ((k2 * 37) % 9 - 4) * 0.025
            L.append(f"\\fill[{ARM_COL[arm]}, opacity=0.6] ({X(m):.3f},{y + jit:.3f}) circle (1.2pt);")
        med = ws[len(ws) // 2]
        L.append(f"\\draw[black, line width=1pt] ({X(med):.3f},{y - 0.14:.2f}) -- ({X(med):.3f},{y + 0.14:.2f});")
        L.append(f"\\node[anchor=west, font=\\tiny] at ({W + 0.05:.2f},{y:.2f}) {{{med:.1f}}};")
    L.append(f"\\node[anchor=north, font=\\tiny] at ({W/2:.2f},{-(n-1)*rowh - 0.45:.2f}) {{minutes per full-system run (log scale), bar and right value: median}};")
    L.append("\\end{tikzpicture}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ deterministic components
def components(res: dict) -> str:
    """Q5: in what share of each configuration's full-system runs each deterministic
    component acted. The layer is the same code for every model; what it has to do is not."""
    from bench.paper_numbers import COMPONENTS
    comps = [c for c, _ in COMPONENTS]
    cols = [("Task 1", "C", ["t1/all/C/F"]), ("Task 1", "T", ["t1/all/T/F"])] + \
           [("Task 2", a, [f"t2/all/{a}/F"]) for a in ("B", "C", "14B", "T")]
    R = res.get("runs", {})
    from bench.paper_numbers import component
    c, rh = 0.62, 0.27
    L = ["% GENERATED - fig:components", "\\begin{tikzpicture}[font=\\scriptsize]"]
    for j, (task, arm, keys) in enumerate(cols):
        L.append(f"\\node[rotate=50, anchor=south west, inner sep=1pt] at ({j*c + c/2 - 0.1:.2f},0.12) {{{task}, {ARM_TXT[arm]}}};")
    for i, comp in enumerate(comps):
        y = -i * rh
        L.append(f"\\node[anchor=east, font=\\tiny] at (-0.05,{y - rh/2:.2f}) {{{comp}}};")
        for j, (task, arm, keys) in enumerate(cols):
            rs = [r for k in keys for r in R.get(k, [])]
            x = j * c
            if not rs:
                L.append(f"\\node[font=\\tiny] at ({x + c/2:.2f},{y - rh/2:.2f}) {{??}};")
                continue
            share = sum(comp in {component(a) for a in r.get("norm", [])} for r in rs) / len(rs)
            L.append(f"\\fill[armC!{int(85 * share)}] ({x + 0.03:.2f},{y - 0.02:.2f}) rectangle ({x + c - 0.03:.2f},{y - rh + 0.02:.2f});")
            if share > 0:
                L.append(f"\\node[font=\\tiny{', text=white' if share > 0.55 else ''}] at ({x + c/2:.2f},{y - rh/2:.2f}) {{{100*share:.0f}}};")
    L.append("\\end{tikzpicture}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ what the analyst receives
def report_listing(res: dict, roots: list[Path]) -> str:
    """Section 'Bounded autonomy': the report the module would have sent for one held-out
    run that ended at analyst support, produced by adapter/report.py from the run record.
    The run: arm C (org9) on the test set r6, Authelia moved to JSON, seed 0 (1 of 2 rules fire)."""
    from adapter.report import render
    TAG, SRC, OLD, SEED = "F-Cr9-p15-r6", "r6_authelia_json", "r6_authelia_text", 0
    rec, rules = None, None
    for r in roots:
        p = r / f"{TAG}.ndjson"
        if p.is_file():
            for line in p.read_text(encoding="utf-8").splitlines():
                x = json.loads(line)
                if x.get("source_id") == SRC and x.get("seed") == SEED:
                    rec = x
            o = r / f"{TAG}.operational.ndjson"
            if o.is_file():
                for line in o.read_text(encoding="utf-8").splitlines():
                    x = json.loads(line)
                    if x.get("source_id") == SRC and x.get("seed") == SEED:
                        rules = x.get("rules")
            break
    if rec is None:
        return ("% GENERATED - lst:report: arm C's run record not found yet\n"
                "\\begin{lstlisting}[float=t, caption={The report written for one held-out run of arm C "
                "that ended at analyst support (pending).}, label=lst:report]\n"
                "(pending: from an arm-C held-out run that ends at analyst support)\n\\end{lstlisting}\n")
    old = json.loads((ROOT / f"testbed/r3/gold/{OLD}.ir.json").read_text())
    deliver = sorted(rec.get("verified_ecs_fields") or [])
    missing = sorted({f["ecs_field"] for f in old["fields"]} - set(deliver) - set((rec.get("scores") or {}).get("correct_fields") or []))
    samples = [json.loads(l)["raw"] for l in (ROOT / f"bench/sources/{SRC}/samples.ndjson").read_text().splitlines()[:2]]
    k, n = (str(rules or "?/?").split("/") + ["?"])[:2]
    case = {"family": "authelia", "source_id": SRC, "record": rec, "new_lines": samples,
            "decision": {"kind": "partial", "deliver": deliver, "missing": missing,
                         "reasons": [f"{k} of {n} detection rules fire; only fields a rule proved are deployed"]},
            "detected_at": "(replayed in evaluation)", "index": "logs-authelia", "samples_k": 6}
    md = render(case)
    keep, skip = [], False
    for ln in md.splitlines():
        if ln.startswith("## What changed"):
            skip = True
        elif ln.startswith("## Fields"):
            skip = False
        elif ln.startswith("## What to do"):
            keep.append("## What to do")
            keep.append("1. The proposal is in candidates/<run>/ir.json - the mapping above, editable. ...")
            break
        if not skip and ln.strip() and not ln.startswith("|---"):
            ln = ln.replace("**", "").replace("`", "")
            keep.append(ln[:96] + (" ..." if len(ln) > 96 else ""))
    body = "\n".join(keep[:34])
    return (f"% GENERATED - lst:report, adapter/report.py over run {TAG} / {SRC} / seed {SEED}\n"
            "\\begin{lstlisting}[float=t, caption={The report the module would have sent the analyst for one held-out run "
            "(Authelia moved to JSON, test set, arm~\\armC{}, full system) that ended at analyst support, written by the system from its run record. "
            "Abridged at the marks. The field table lists every mapping and whether it went live.}, label=lst:report, "
            "basicstyle=\\scriptsize\\ttfamily, breaklines=true, frame=single, columns=fullflexible, belowcaptionskip=14pt, framesep=3pt]\n" + body + "\n\\end{lstlisting}\n")


